def build_matrix() -> MaturityMatrix:
    cells: list[MaturityCell] = []
    for domain in DOMAINS:
        for aspect in ASPECTS:
            for level in (1, 2, 3, 4):
                key = (domain.id.value, aspect.id.value, level)
                cells.append(
                    MaturityCell(
                        domain_id=domain.id,
                        aspect_id=aspect.id,
                        level=level,
                        description=_CELLS[key],
                    )
                )
    return MaturityMatrix(
        title="Матрица оценки зрелости агентного управления",
        rule=(
            "Оценка области — минимум из трёх аспектов, не среднее. "
            "Самое слабое звено определяет, чем система действительно способна управлять."
        ),
        domains=DOMAINS,
        aspects=ASPECTS,
        levels=LEVELS,
        cells=cells,
    )
